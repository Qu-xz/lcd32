// 查找字符在字库中的索引
int chinese_find_char_index(const char *str, const chinese_font_t *font) {
    int char_len = 3;  // UTF-8中文字符是3字节
    int map_len = strlen(font->char_map);

    for (int i = 0; i < map_len; i += 3) {
        // 比较UTF-8字符（3字节）
        if (i + 2 < map_len) {
            if (str[0] == font->char_map[i] &&
                str[1] == font->char_map[i + 1] &&
                str[2] == font->char_map[i + 2]) {
                return i / 3;  // 返回字符索引
            }
        }
    }
    return -1;  // 未找到
}

// 绘制单个汉字
void chinese_draw_char(uint16_t x, uint16_t y, const char *str, const chinese_font_t *font, uint16_t color, uint16_t bg_color) {
    int index = chinese_find_char_index(str, font);

    if (index < 0) {
        return;  // 字符不存在
    }

    const uint8_t *glyph_data = font->glyph_data + index * (font->width * font->height / 8);

    // 16x16汉字：每行2字节，共16行
    for (int row = 0; row < font->height; row++) {
        uint8_t byte1 = glyph_data[row * 2];  // 左8个像素
        uint8_t byte2 = glyph_data[row * 2 + 1];  // 右8个像素

        // 绘制左8个像素（byte1），正常顺序
        for (int col = 0; col < 8; col++) {
            if (byte1 & (0x80 >> col)) {
                lcd_draw_pixel(x + col, y + row, color);
            } else if (bg_color != 0xFFFF) {
                lcd_draw_pixel(x + col, y + row, bg_color);
            }
        }

        // 绘制右8个像素（byte2），正常顺序
        for (int col = 0; col < 8; col++) {
            if (byte2 & (0x80 >> col)) {
                lcd_draw_pixel(x + 8 + col, y + row, color);
            } else if (bg_color != 0xFFFF) {
                lcd_draw_pixel(x + 8 + col, y + row, bg_color);
            }
        }
    }
}

// 绘制中文字符串（支持混合ASCII字符）
void chinese_draw_string(uint16_t x, uint16_t y, const char *str, const chinese_font_t *font, uint16_t color, uint16_t bg_color) {
    uint16_t pos_x = x;
    const char *p = str;

    while (*p) {
        // 检查是否是UTF-8中文字符（3字节，以0xE0开头）
        if ((*p & 0xE0) == 0xE0 && p[1] && p[2]) {
            // 绘制汉字
            chinese_draw_char(pos_x, y, p, font, color, bg_color);
            pos_x += font->width;
            p += 3;
        } else if (*p >= 32 && *p <= 126) {
            // ASCII可打印字符，使用8x13英文字体
            u8g2_draw_char(pos_x, y + 2, *p, &u8g2_font_8x13_tf, color, bg_color);
            pos_x += 8;
            p++;
        } else {
            // 其他字符，跳过
            p++;
        }
    }
}

// 计算混合字符串宽度
static int chinese_string_width(const char *str, const chinese_font_t *font) {
    int width = 0;
    const char *p = str;

    while (*p) {
        if ((*p & 0xE0) == 0xE0 && p[1] && p[2]) {
            width += font->width;
            p += 3;
        } else if (*p >= 32 && *p <= 126) {
            width += 8;  // ASCII字符宽度
            p++;
        } else {
            p++;
        }
    }
    return width;
}

// 居中绘制中文字符串（支持混合ASCII字符）
void chinese_draw_string_centered(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const char *str, const chinese_font_t *font, uint16_t color, uint16_t bg_color) {
    int str_width = chinese_string_width(str, font);
    int str_height = font->height;

    uint16_t start_x = x + (w - str_width) / 2;
    uint16_t start_y = y + (h - str_height) / 2;

    chinese_draw_string(start_x, start_y, str, font, color, bg_color);
}
