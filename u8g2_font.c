// 绘制单个字符
void u8g2_draw_char(uint16_t x, uint16_t y, int c, const u8g2_font_t *font, uint16_t color, uint16_t bg_color) {
    // 根据字体类型选择不同的绘制方法
    if (font->width == 20 && font->height == 40) {
        // 20x40字体 - 为数字和特殊字符设计
        int char_idx;
        if (c >= '0' && c <= '9') {
            char_idx = c - '0';  // 数字0-9对应索引0-9
        } else if (c == 176) {  // ° 符号
            char_idx = 10;
        } else {
            char_idx = 0;
        }

        const uint8_t *glyph_data = font_20x40_nums[char_idx];
        
        // 120字节格式：每行3字节（24位，只用前20位）
        for (int row = 0; row < 40; row++) {
            int base_byte = row * 3;  // 每行3字节
            
            for (int col = 0; col < 20; col++) {
                int byte_offset = col / 8;
                int bit_idx = 7 - (col % 8);
                int actual_byte = base_byte + byte_offset;
                
                if (glyph_data[actual_byte] & (1 << bit_idx)) {
                    lcd_draw_pixel(x + col, y + row, color);
                } else if (bg_color != 0xFFFF) {
                    lcd_draw_pixel(x + col, y + row, bg_color);
                }
            }
        }
    } else {
        // 8x16字体
        if (c < font->start_char || c > font->end_char) {
            c = ' ';  // 替换为空格
        }
        const uint8_t *glyph_data = font_8x16[c - 32];

        for (int row = 0; row < font->height; row++) {
            uint8_t line = glyph_data[row];
            for (int col = 0; col < font->width; col++) {
                // 正常顺序绘制（从左到右）
                if (line & (0x80 >> col)) {
                    lcd_draw_pixel(x + col, y + row, color);
                } else if (bg_color != 0xFFFF) {
                    lcd_draw_pixel(x + col, y + row, bg_color);
                }
            }
        }
    }
}

// 绘制字符串（从左到右）
void u8g2_draw_string(uint16_t x, uint16_t y, const char *str, const u8g2_font_t *font, uint16_t color, uint16_t bg_color) {
    uint16_t pos_x = x;
    int len = strlen(str);
    for (int i = 0; i < len; i++) {
        u8g2_draw_char(pos_x, y, str[i], font, color, bg_color);
        pos_x += font->width;
    }
}

// 居中绘制字符串
void u8g2_draw_string_centered(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const char *str, const u8g2_font_t *font, uint16_t color, uint16_t bg_color) {
    int len = strlen(str);
    int str_width = len * font->width;
    int str_height = font->height;

    uint16_t start_x = x + (w - str_width) / 2;
    uint16_t start_y = y + (h - str_height) / 2;

    u8g2_draw_string(start_x, start_y, str, font, color, bg_color);
}

// 获取字符串宽度
uint16_t u8g2_get_string_width(const char *str, const u8g2_font_t *font) {
    return strlen(str) * font->width;
}

// 绘制温度字符串（带°符号）
void u8g2_draw_temp_string(uint16_t x, uint16_t y, const char *temp_str, uint16_t color, uint16_t bg_color) {
    uint16_t pos_x = x;
    int len = strlen(temp_str);
    
    // 先绘制温度数字
    for (int i = 0; i < len; i++) {
        if (temp_str[i] >= '0' && temp_str[i] <= '9') {
            u8g2_draw_char(pos_x, y, temp_str[i], &u8g2_font_20x40_nums, color, bg_color);
            pos_x += u8g2_font_20x40_nums.width;
        }
    }
    
    // 绘制°符号（稍微偏上一点，作为上角标）
    u8g2_draw_char(pos_x, y - 15, 176, &u8g2_font_20x40_nums, color, bg_color);
    pos_x += u8g2_font_20x40_nums.width / 2; // °符号宽度较小
    
    // 绘制C
    u8g2_draw_char(pos_x, y, 'C', &u8g2_font_20x40_nums, color, bg_color);
}