// 绘制单个字符
void lcd_draw_char(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg_color) {
    if (c < 32 || c > 127) c = 32;  // 非打印字符替换为空格

    const uint8_t *font_data = font_8x16[c - 32];

    for (int row = 0; row < 16; row++) {
        uint8_t line = font_data[row];
        for (int col = 0; col < 8; col++) {
            if (line & (0x80 >> col)) {
                lcd_draw_pixel(x + col, y + row, color);
            } else if (bg_color != 0xFFFF) {  // 0xFFFF表示透明背景
                lcd_draw_pixel(x + col, y + row, bg_color);
            }
        }
    }
}

// 绘制字符串
void lcd_draw_string(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg_color) {
    uint16_t pos_x = x;
    while (*str) {
        lcd_draw_char(pos_x, y, *str, color, bg_color);
        pos_x += 8;
        str++;
    }
}

// 居中绘制字符串
void lcd_draw_string_centered(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const char *str, uint16_t color, uint16_t bg_color) {
    int len = strlen(str);
    int str_width = len * 8;
    int str_height = 16;

    uint16_t start_x = x + (w - str_width) / 2;
    uint16_t start_y = y + (h - str_height) / 2;

    lcd_draw_string(start_x, start_y, str, color, bg_color);
}